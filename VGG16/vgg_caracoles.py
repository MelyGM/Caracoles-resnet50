    plt.ylabel('Precisión' if metrica == 'accuracy' else 'Pérdida')
    plt.legend()
    plt.grid(True, linestyle='--', alpha=0.6)
    plt.tight_layout()
    plt.savefig(archivo, dpi=150)
    plt.show()


